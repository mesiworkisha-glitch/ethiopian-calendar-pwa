function escapeHtml(str) {
    const div = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
    return String(str).replace(/[&<>"']/g, ch => div[ch]);
}

function handleSharedContent() {
    // Companion to manifest.json's `share_target` (method: GET) — when the
    // OS "Share" sheet launches this PWA with shared text/title/url, we
    // can't reliably auto-parse arbitrary shared text into a specific
    // calendar date, so instead we surface what was shared and land on the
    // Converter tab, letting the person manually enter the relevant date.
    let params;
    try { params = new URLSearchParams(window.location.search); } catch (e) { return; }
    const sharedTitle = params.get('title'), sharedText = params.get('text'), sharedUrl = params.get('url');
    if (!sharedTitle && !sharedText && !sharedUrl) return;

    const targetBtn = document.querySelector('.nav-btn[data-target="tab-converter"]');
    if (targetBtn) targetBtn.click();

    const out = document.getElementById('converter-output');
    if (out) {
        const parts = [sharedTitle, sharedText, sharedUrl].filter(Boolean).map(escapeHtml).join(' — ');
        out.innerHTML = `<p class="shared-content-notice"><strong>${t('shared_content_received')}</strong> ${parts}</p>`;
    }
}

function setupTabs() {
    document.querySelectorAll('.nav-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            let targetId = btn.getAttribute('data-target') || btn.dataset.target; if (!targetId) return;
            document.querySelectorAll('.nav-btn').forEach(b => { b.classList.remove('active'); b.setAttribute('aria-selected', 'false'); });
            document.querySelectorAll('.tab-content').forEach(t => { t.classList.remove('active'); t.hidden = true; });
            btn.classList.add('active'); btn.setAttribute('aria-selected', 'true');
            let contentTab = document.getElementById(targetId); if (contentTab) { contentTab.classList.add('active'); contentTab.hidden = false; }
        });
    });

    // Deep-link support: ?tab=converter (etc.) opens straight to that tab.
    // This is what makes the PWA manifest's "shortcuts" (long-press the
    // home-screen icon) actually useful, and lets anyone share a link
    // straight to, say, the Converter instead of always landing on Today.
    try {
        const requestedTab = new URLSearchParams(window.location.search).get('tab');
        if (requestedTab) {
            const targetBtn = document.querySelector(`.nav-btn[data-target="tab-${requestedTab}"]`);
            if (targetBtn) targetBtn.click();
        }
    } catch (e) { /* malformed URL or no query string — just show the default tab */ }
}

