let synaxariumData = null;
let synaxariumLoadFailed = false;
async function loadSynaxarium() {
    if (synaxariumData) return synaxariumData;
    try {
        synaxariumData = await (await fetch('synaxarium_feasts.json')).json();
        synaxariumLoadFailed = false;
    } catch (e) {
        // Don't cache the failure as if it were valid (empty) data — leaving
        // synaxariumData as null means the next call will retry the fetch
        // instead of silently treating "network failed" the same as
        // "there are genuinely no entries today" for the rest of the session.
        synaxariumData = null;
        synaxariumLoadFailed = true;
    }
    return synaxariumData || {};
}

